static bool sendDpcOn() {
  // Equivalent clear payload before NinebotCrypto:
  //   5A A5 02 3E 20 03 76 01 00
  // The raw legacy CRC bytes 25 FF are not appended here. encryptPacket()
  // supplies the authenticated trailer required by the active BLE session.
  const uint8_t value[2] = { 0x01, 0x00 };
  Serial.println();
  Serial.println("=== DPC: setze ESC 0x76 = 0x0001 ===");
  return sendNinebotPacket(DEV_ESC, CMD_WRITE, REG_DPC, value, sizeof(value));
}

uint32_t littleEndianValue(const uint8_t* data, size_t len) {
  uint32_t value = 0;

  if (len > 4) len = 4;

  for (size_t i = 0; i < len; ++i) {
    value |= ((uint32_t)data[i]) << (8 * i);
  }

  return value;
}

void handleTelemetryReply(const uint8_t* plain, size_t len) {
  if (len < 7) return;

  const uint8_t src = plain[3];
  const uint8_t dst = plain[4];
  const uint8_t cmd = plain[5];
  const uint8_t reg = plain[6];
  const uint8_t dataLen = plain[2];

  if (dst != DEV_PHONE || cmd != CMD_READ_ACK) return;
  if (len < 7 + dataLen) return;

  const uint8_t* data = plain + 7;
  telemetryWaiting = false;

  if (src == DEV_ESC && reg == REG_DPC && dataLen >= 2) {
    uint16_t raw = (uint16_t)littleEndianValue(data, 2);
    Serial.printf(">>> DPC READBACK 0x76 = 0x%04X (%u)\n", (unsigned)raw, (unsigned)raw);

    if (raw == 1) {
      dpcState = DPC_CONFIRMED;
      dpcAttempts = 0;
      Serial.println("*** DPC 0x76 bestaetigt: EIN ***");
    } else if (dpcAttempts < DPC_MAX_ATTEMPTS) {
      dpcState = DPC_NEED_WRITE;
      dpcLastAction = millis();
      Serial.println("DPC ist noch nicht 1 -> setze erneut.");
    } else {
      dpcState = DPC_FAILED;
      Serial.println("WARN: DPC 0x76 nach 5 Versuchen nicht bestaetigt; Telemetrie laeuft weiter.");
    }
    return;
  }

  if (src == DEV_ESC && reg == REG_MODE && dataLen >= 2) {
    uint16_t raw = (uint16_t)littleEndianValue(data, 2);
    int8_t mode = -1;

    // Ninebot current-operation mode (0x1F):
    //   0 = NORMAL/Drive, 1 = ECO, 2 = SPORT
    if (raw <= 2) mode = (int8_t)raw;

    if (NB_TELEMETRY_DEBUG) Serial.printf(">>> DRIVE MODE raw=%u -> %s\n",
                  (unsigned)raw,
                  mode == 0 ? "DRIVE" : mode == 1 ? "ECO" : mode == 2 ? "SPORT" : "UNKNOWN");

    portENTER_CRITICAL(&telemetryMux);
    telemetrySnapshot.ride_mode = mode;
    telemetrySnapshot.last_update_ms = millis();
    telemetrySnapshot.sequence++;
    portEXIT_CRITICAL(&telemetryMux);
    return;
  }

  if (src == DEV_ESC && reg == REG_SPEED && dataLen >= 2) {
    int16_t raw = (int16_t)littleEndianValue(data, 2);
    float value = raw / 10.0f;
    if (NB_TELEMETRY_DEBUG) Serial.printf(">>> SPEED: %.1f km/h\n", value);
    portENTER_CRITICAL(&telemetryMux);
    telemetrySnapshot.speed_kmh = value;
    telemetrySnapshot.last_update_ms = millis();
    telemetrySnapshot.sequence++;
    portEXIT_CRITICAL(&telemetryMux);
    return;
  }

  if (src == DEV_ESC && reg == REG_ODO_LO && dataLen >= 2) {
    odoLow = (uint16_t)littleEndianValue(data, 2);
    haveOdoLow = true;

    if (haveOdoHigh) {
      uint32_t metres = ((uint32_t)odoHigh << 16) | odoLow;
      float value = metres / 1000.0f;
      if (NB_TELEMETRY_DEBUG) Serial.printf(">>> ODO: %.3f km\n", value);
      portENTER_CRITICAL(&telemetryMux);
      telemetrySnapshot.odometer_km = value;
      telemetrySnapshot.last_update_ms = millis();
      telemetrySnapshot.sequence++;
      portEXIT_CRITICAL(&telemetryMux);
    }
    return;
  }

  if (src == DEV_ESC && reg == REG_ODO_HI && dataLen >= 2) {
    odoHigh = (uint16_t)littleEndianValue(data, 2);
    haveOdoHigh = true;

    if (haveOdoLow) {
      uint32_t metres = ((uint32_t)odoHigh << 16) | odoLow;
      float value = metres / 1000.0f;
      if (NB_TELEMETRY_DEBUG) Serial.printf(">>> ODO: %.3f km\n", value);
      portENTER_CRITICAL(&telemetryMux);
      telemetrySnapshot.odometer_km = value;
      telemetrySnapshot.last_update_ms = millis();
      telemetrySnapshot.sequence++;
      portEXIT_CRITICAL(&telemetryMux);
    }
    return;
  }

  if (src == DEV_BATT && reg == REG_BAT_PCT && dataLen >= 2) {
    uint16_t pct = (uint16_t)littleEndianValue(data, 2);
    if (NB_TELEMETRY_DEBUG) Serial.printf(">>> AKKU: %u %%\n", (unsigned)pct);
    portENTER_CRITICAL(&telemetryMux);
    telemetrySnapshot.battery_percent = (float)pct;
    telemetrySnapshot.last_update_ms = millis();
    telemetrySnapshot.sequence++;
    portEXIT_CRITICAL(&telemetryMux);
    return;
  }

  if (src == DEV_BATT && reg == REG_BAT_CUR && dataLen >= 2) {
    int16_t raw = (int16_t)littleEndianValue(data, 2);
    float value = raw / 100.0f;
    if (NB_TELEMETRY_DEBUG) Serial.printf(">>> BAT CURRENT: %.2f A\n", value);
    portENTER_CRITICAL(&telemetryMux);
    telemetrySnapshot.battery_current_a = value;
    telemetrySnapshot.last_update_ms = millis();
    telemetrySnapshot.sequence++;
    portEXIT_CRITICAL(&telemetryMux);
    return;
  }

  if (src == DEV_BATT && reg == REG_BAT_VOLT && dataLen >= 2) {
    uint16_t raw = (uint16_t)littleEndianValue(data, 2);
    float value = raw / 100.0f;
    if (NB_TELEMETRY_DEBUG) Serial.printf(">>> BAT VOLTAGE: %.2f V\n", value);
    portENTER_CRITICAL(&telemetryMux);
    telemetrySnapshot.voltage_v = value;
    telemetrySnapshot.last_update_ms = millis();
    telemetrySnapshot.sequence++;
    portEXIT_CRITICAL(&telemetryMux);
    return;
  }

  if (src == DEV_BATT && reg == REG_BAT_TEMP && dataLen >= 2) {
    int t1 = (int)data[0] - 20;
    int t2 = (int)data[1] - 20;
    float value = (t1 + t2) * 0.5f;
    if (NB_TELEMETRY_DEBUG) Serial.printf(">>> BAT TEMP: %d / %d C\n", t1, t2);
    portENTER_CRITICAL(&telemetryMux);
    telemetrySnapshot.bms_temp_c = value;
    telemetrySnapshot.last_update_ms = millis();
    telemetrySnapshot.sequence++;
    portEXIT_CRITICAL(&telemetryMux);
    return;
  }

  Serial.printf(">>> READ src=0x%02X reg=0x%02X: ", src, reg);
  dumpHex("", data, dataLen);
}

// ============================================================
// Plain decrypted packet handler
// ============================================================

void handlePlainPacket(const uint8_t* plain,
                       size_t len,
                       uint32_t counter) {
  if (NB_PACKET_DEBUG) {
    Serial.println();
    Serial.printf("RX decrypted, counter=%lu, local msgIt=%lu\n",
                  (unsigned long)counter, (unsigned long)msgIt);
    dumpHex("RX PLAIN: ", plain, len);
  }

  if (len < 7) return;

  uint8_t src = plain[3];
  uint8_t dst = plain[4];
  uint8_t cmd = plain[5];
  uint8_t arg = plain[6];

  if (NB_PACKET_DEBUG) Serial.printf("SRC=0x%02X DST=0x%02X CMD=0x%02X ARG=0x%02X LEN=%u\n",
                                    src,dst,cmd,arg,plain[2]);

  // Passive G30 dashboard-status frame. On the internal Ninebot bus the ESC
  // sends command 0x64 to the BLE/dashboard board; byte 9 is the headlight
  // state (0/1). Some BLE firmwares forward this frame to the phone session,
  // others do not. When we see it, use it without sending any extra command.
  if (src == DEV_ESC && dst == DEV_BLE && cmd == 0x64 && len >= 13 && plain[2] >= 6) {
    const bool light = plain[9] != 0;
    Serial.printf(">>> DASH LIGHT: %s (passive 0x64)\n", light ? "ON" : "OFF");
    portENTER_CRITICAL(&telemetryMux);
    telemetrySnapshot.headlight_on = light;
    telemetrySnapshot.headlight_valid = true;
    telemetrySnapshot.sequence++;
    portEXIT_CRITICAL(&telemetryMux);
    return;
  }

  // ----------------------------------------------------------
  // INIT response
  // ----------------------------------------------------------
  if (src == DEV_BLE &&
      dst == DEV_PHONE &&
      cmd == CMD_INIT &&
      haveInitData) {

    Serial.println();
    Serial.println("*** NinebotCrypto INIT OK ***");

    dumpHex("BLE random/key: ", randomBleData, 16);

    char serialText[15] = {0};
    memcpy(serialText, scooterSerial, 14);

    Serial.print("Scooter S/N: ");
    Serial.println(serialText);

    Serial.printf("0x5B ARG = 0x%02X\n", arg);

    // v7.14 auto-auth priority:
    // 1) Explicit real Segway app key, if provisioned.
    // 2) Our own key from the last SUCCESSFUL button pairing with this exact
    //    scooter serial. Try it exactly like a bound app: no 0x5C, direct 0x5D.
    // 3) Fresh-key + one-time button pairing fallback.
    if (haveSegwayAppKey && !segwayKeyRejectedThisBoot) {
      memcpy(randomAppData, segwayAppKey, sizeof(randomAppData));
      haveAppKey = true;
      usingStoredAppKey = false;
      directSegwayAuth = true;
      directStoredAuth = false;
      pairRetryCount = 0;
      calcSha1Key(randomAppData, randomBleData);
      Serial.println("[AUTH-APP] Echter Segway-App-Key -> direkter 0x5D-Login ohne 0x5C/Powerbutton.");
      authState = AUTH_WAIT_PAIR;
      authLastSend = millis();
      pendingTx = TX_PAIR;
    } else if (!storedKeyRejectedThisBoot && loadStoredAppKeyForScooter()) {
      directSegwayAuth = false;
      directStoredAuth = true;
      pairRetryCount = 0;
      calcSha1Key(randomAppData, randomBleData);
      Serial.println("[AUTH-AUTO] Gebundener Dashboard-Key -> direkter 0x5D-Reconnect ohne 0x5C/Powerbutton.");
      authState = AUTH_WAIT_PAIR;
      authLastSend = millis();
      pendingTx = TX_PAIR;
    } else {
      usingStoredAppKey = false;
      directSegwayAuth = false;
      directStoredAuth = false;
      Serial.println("[AUTH] Noch kein akzeptierter Reconnect-Key -> frischer 0x3E-Key; Powerbutton einmalig noetig.");
      createAppKey();
      Serial.println("Plane 0x5C ausserhalb des Notify-Callbacks ein.");
      authState = AUTH_WAIT_PING;
      authLastSend = millis();
      pendingTx = TX_PING;
    }

    return;
  }

  // ----------------------------------------------------------
  // PING/AUTH response
  // ----------------------------------------------------------
  if (src == DEV_BLE &&
      dst == DEV_PHONE &&
      cmd == CMD_PING) {

    if (arg == 0x01) {
      Serial.println();
      Serial.println("*** 0x5C01: Power/Auth bestaetigt ***");
      Serial.println("Plane 0x5D ausserhalb des Notify-Callbacks ein.");

      authState = AUTH_WAIT_PAIR;
      authLastSend = millis();
      pendingTx = TX_PAIR;
    }
    else {
      Serial.println();
      Serial.println("*** 0x5C00: Scooter wartet auf Pairing-Bestaetigung. ***");
      if (usingStoredAppKey) {
        Serial.println("[AUTH-NVS] Gespeicherter Key wurde erkannt, Scooter verlangt aber erneut physische Bestaetigung.");
      }
      Serial.println(">>> Power-Taste am Scooter kurz druecken, falls 0x5C00 bestehen bleibt. <<<");
      Serial.println("0x5C wird bis zur Bestaetigung erneut gesendet.");

      authState = AUTH_WAIT_PING;
      authLastSend = millis();
    }

    return;
  }

  // ----------------------------------------------------------
  // PAIR response
  // ----------------------------------------------------------
  if (src == DEV_BLE &&
      dst == DEV_PHONE &&
      cmd == CMD_PAIR) {

    if (arg == 0x01) {
      authState = AUTH_READY;
      readySince = millis();
      telemetrySetLink(true, true);

      if (foundDevice && foundDevice->haveName()) {
        saveBoundScooterTargetName(foundDevice->getName().c_str());
      }

      // A fresh button pairing that reaches 0x5D01 has proven that THIS key was
      // accepted by the scooter. Persist it for the next boot and try it as a
      // bound direct-PAIR credential before asking for the button again.
      if (!directSegwayAuth && !directStoredAuth) {
        saveStoredAppKeyForScooter();
        Serial.println("[AUTH-AUTO] Erstpairing akzeptiert; naechster Start versucht Auto-Auth ohne Powerbutton.");
      } else if (directStoredAuth) {
        Serial.println("[AUTH-AUTO] AUTO-AUTH ERFOLGREICH: gespeicherter Dashboard-Key akzeptiert, kein Powerbutton.");
      } else if (directSegwayAuth) {
        Serial.println("[AUTH-APP] Direkter 0x5D-Login akzeptiert: buttonlose Auth aktiv.");
      }

      Serial.println();
      Serial.println("==============================================");
      Serial.println("*** AUTHENTIFIZIERUNG ERFOLGREICH - READY ***");
      Serial.println("==============================================");
      Serial.println("Auth READY. Setze und pruefe DPC-Register 0x76, danach startet Telemetrie ...");

      telemetryWaiting = false;
      lastTelemetry = 0;
      telemetryStep = 0;
      dpcAttempts = 0;
      dpcLastAction = 0;
      dpcLastPeriodicCheck = millis();
      dpcState = DPC_NEED_WRITE;
    }
    else {
      if (directSegwayAuth) {
        Serial.printf("[AUTH-APP] Direkter 0x5D-Login abgelehnt (ARG=0x%02X) -> Button-Fallback.\n", arg);
        segwayKeyRejectedThisBoot = true;
        directSegwayAuth = false;
        pClient->disconnect();
      } else if (directStoredAuth) {
        Serial.printf("[AUTH-AUTO] Gespeicherter Dashboard-Key abgelehnt (ARG=0x%02X) -> loesche Key und paare einmal neu.\n", arg);
        storedKeyRejectedThisBoot = true;
        clearStoredAppKeyForScooter();
        pClient->disconnect();
      } else {
        Serial.printf("PAIR Antwort ARG=0x%02X; versuche erneut.\n", arg);
        authState = AUTH_WAIT_PAIR;
        authLastSend = millis();
      }
    }

    return;
  }

  // ----------------------------------------------------------
  // Telemetry
  // ----------------------------------------------------------
  handleTelemetryReply(plain, len);
}

// ============================================================
// Complete encrypted frame processor
// ============================================================

void processEncryptedFrame(const uint8_t* frame, size_t len) {
  if (NB_PACKET_DEBUG) { Serial.println(); dumpHex("RX ENC FULL: ", frame, len); }

  uint8_t plain[192];
  uint32_t counter = 0;

  size_t plainLen = decryptPacket(
    frame,
    len,
    plain,
    sizeof(plain),
    counter
  );

  if (plainLen == 0) {
    Serial.println("RX konnte nicht entschluesselt werden.");
    return;
  }

  handlePlainPacket(plain, plainLen, counter);
}

// ============================================================
// Notify callback + fragment reassembly
// ============================================================

void notifyCallback(BLERemoteCharacteristic* c,
                    uint8_t* data,
                    size_t length,
                    bool isNotify) {
  if (NB_PACKET_DEBUG) {
    Serial.printf("RX BLE chunk: %u B\n", (unsigned)length);
    dumpHex("  RX chunk: ", data, length);
  }

  // A new encrypted Ninebot packet starts with 5A A5
  if (length >= 2 &&
      data[0] == 0x5A &&
      data[1] == 0xA5) {

    rxLen = 0;
    rxExpected = 0;
  }

  if (rxLen + length > sizeof(rxBuffer)) {
    Serial.println("RX buffer overflow -> reset.");
    rxLen = 0;
    rxExpected = 0;
    return;
  }

  memcpy(rxBuffer + rxLen, data, length);
  rxLen += length;

  if (rxLen >= 3 && rxExpected == 0) {
    // encrypted total = dataLen + 13
    rxExpected = (size_t)rxBuffer[2] + 13;

    if (NB_PACKET_DEBUG) Serial.printf("RX erwartet insgesamt %u B\n", (unsigned)rxExpected);

    if (rxExpected > sizeof(rxBuffer)) {
      Serial.println("Unplausible RX-Laenge -> reset.");
      rxLen = 0;
      rxExpected = 0;
      return;
    }
  }

  if (rxExpected > 0 && rxLen >= rxExpected) {
    processEncryptedFrame(rxBuffer, rxExpected);

    size_t leftover = rxLen - rxExpected;

    if (leftover > 0) {
      memmove(
        rxBuffer,
        rxBuffer + rxExpected,
        leftover
      );
    }

    rxLen = leftover;
    rxExpected = 0;
  }
}

