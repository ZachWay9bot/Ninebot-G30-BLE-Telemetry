void ninebotTelemetryLoop() {
  // Never destroy BLE objects from onDisconnect(). The callback runs inside the
  // BLE stack; cleanup here after it has returned. BLEClient's destructor also
  // unregisters the GATT client, which prevents stale clients accumulating.
  if (clientCleanupPending && !isConnected && !scanRunning) {
    if (pClient) {
      Serial.println("[BLE-RECOVER] Raeume getrennten BLEClient auf.");
      delete pClient;
      pClient = nullptr;
    }
    clientCleanupPending = false;
  }

  if (doConnect && !scanRunning) {
    doConnect = false;

    if (!connectScooter()) {
      delay(1000);
    }
  }

  // Keep all GATT writes in normal task/loop context, never in notifyCallback().
  servicePendingTx();
  serviceAuth();
  serviceDpc();
  serviceTelemetry();

  if (!isConnected &&
      !doConnect &&
      !scanRunning &&
      authState == AUTH_IDLE) {

    // Give the scooter and the controller a short moment to finish the previous
    // link teardown before scanning again. Immediate rescans are surprisingly
    // good at finding absolutely nothing.
    if (disconnectedAtMs != 0 &&
        (uint32_t)(millis() - disconnectedAtMs) < RECONNECT_SETTLE_MS) {
      return;
    }

    Serial.println("[AUTOCONNECT] Scooter offline/nicht sichtbar -> scanne weiter ...");
    startScanAsync(5);
  }
}

